#include <stdio.h>

int main(void)
{
    int n, a;
    scanf("%d", &n);

    if (n <= 100000)
    {
        a = n * 0.1;
        printf("%d\n", a);
    }
    else if (n > 100000)
    {
        if (n <= 200000)
        {
            a = 100000 * 0.1 + (n - 100000) * 0.075;
            printf("%d\n", a);
        }
        else if (n > 200000)
        {
            if (n <= 400000)
            {
                a = 100000 * 0.1 + 100000 * 0.075 + (n - 200000) * 0.05;
                printf("%d\n", a);
            }
            else if (n > 400000)
            {
                if (n <= 600000)
                {
                    a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + (n - 400000) * 0.03;
                    printf("%d\n", a);
                }
                else if (n > 600000)
                {
                    if (n <= 1000000)
                    {
                        a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + 200000 * 0.03 + (n - 600000) * 0.015;
                        printf("%d\n", a);
                    }
                    else if (n > 1000000)
                    {
                        a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + 200000 * 0.03 + 400000 * 0.015 + (n - 1000000) * 0.01;
                        printf("%d\n", a);
                    }
                }
            }
        }
    }

    return 0;
}