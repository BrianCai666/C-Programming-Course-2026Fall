#include <iostream>
using namespace std;

int main(void)
{
   int n, a;
    cin >> n;

    if (n <= 100000)
    {
        a = n * 0.1;
        cout << a << endl;
    }
    else if (n > 100000)
    {
        if (n <= 200000)
        {
            a = 100000 * 0.1 + (n - 100000) * 0.075;
            cout << a << endl;
        }
        else if (n > 200000)
        {
            if (n <= 400000)
            {
                a = 100000 * 0.1 + 100000 * 0.075 + (n - 200000) * 0.05;
                cout << a << endl;
            }
            else if (n > 400000)
            {
                if (n <= 600000)
                {
                    a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + (n - 400000) * 0.03;
                    cout << a << endl;
                }
                else if (n > 600000)
                {
                    if (n <= 1000000)
                    {
                        a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + 200000 * 0.03 + (n - 600000) * 0.015;
                        cout << a << endl;
                    }
                    else if (n > 1000000)
                    {
                        a = 100000 * 0.1 + 100000 * 0.075 + 200000 * 0.05 + 200000 * 0.03 + 400000 * 0.015 + (n - 1000000) * 0.01;
                        cout << a << endl;
                    }
                }
            }
        }
    }

    return 0;
}